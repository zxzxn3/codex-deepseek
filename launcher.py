#!/usr/bin/env python3
"""An isolated Codex CLI home for DeepSeek; never changes ~/.codex."""
from __future__ import annotations

import datetime
import getpass
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tomllib
import warnings

HERE = Path(__file__).resolve().parent
DATA = HERE / ".codex"
KEY_ATTRIBUTES = ["application", "codex-deepseek", "provider", "deepseek"]
MODELS = ("deepseek-flash", "deepseek-v4-pro")


def catalog() -> dict:
    # Vendored official model metadata; no external project dependency.
    result = json.loads((HERE / "models.json").read_text())
    if {m["slug"] for m in result["models"]} != set(MODELS):
        raise ValueError("Upstream model catalog changed; review before installing")
    return result


def toml_config(data: dict) -> str:
    """Serialize parsed configuration values; comments and formatting are not copied."""
    def value(item):
        if isinstance(item, str):
            return json.dumps(item)
        if isinstance(item, bool):
            return 'true' if item else 'false'
        if isinstance(item, (int, float)):
            return repr(item)
        if isinstance(item, (datetime.datetime, datetime.date, datetime.time)):
            return item.isoformat()
        if isinstance(item, list):
            return '[' + ', '.join(value(v) for v in item) + ']'
        if isinstance(item, dict):
            return '{' + ', '.join(json.dumps(k) + ' = ' + value(v)
                                   for k, v in item.items()) + '}'
        raise ValueError(f'Unsupported configuration value type: {type(item).__name__}')

    lines = []

    def table(items, path=()):
        if path:
            lines.append('[' + '.'.join(json.dumps(k) for k in path) + ']')
        for key, item in items.items():
            if not isinstance(item, dict):
                lines.append(json.dumps(key) + ' = ' + value(item))
        for key, item in items.items():
            if isinstance(item, dict):
                lines.append('')
                table(item, (*path, key))

    table(data)
    return '\n'.join(lines).rstrip() + '\n'


def configuration(base: str = '', *, root: Path | None = None) -> str:
    """Keep Codex defaults, or copied preferences, except required DeepSeek wiring."""
    data = tomllib.loads(base)
    # Named profiles live in separate files and can replace the provider settings.
    # Copying their selection without those files would not be a usable install.
    data.pop('profile', None)
    hooks = data.get('hooks', {})
    if isinstance(hooks, dict):
        hooks.pop('state', None)  # Approval records belong to the source config path.
    data.update(model='deepseek-flash', model_provider='deepseek',
                model_catalog_json=str((root or HERE) / 'models.json'))
    providers = data.setdefault('model_providers', {})
    if not isinstance(providers, dict):
        raise ValueError('model_providers must be a table')
    providers['deepseek'] = {
        'name': 'DeepSeek', 'base_url': 'https://api.deepseek.com',
        'wire_api': 'responses', 'requires_openai_auth': False,
        'supports_websockets': False,
        'auth': {'command': shutil.which('secret-tool') or '/usr/bin/secret-tool',
                 'args': ['lookup', *KEY_ATTRIBUTES], 'refresh_interval_ms': 0},
    }
    result = ('# Generated by codex-deepseek/install.py.\n'
              '# Only DeepSeek connection settings override Codex defaults or copied preferences.\n'
              + toml_config(data))
    tomllib.loads(result)
    return result


def save_key() -> None:
    if not sys.stdin.isatty():
        raise ValueError("Run codex-deepseek setup-key in an interactive terminal")
    with warnings.catch_warnings():
        warnings.simplefilter('error', getpass.GetPassWarning)
        try:
            key = getpass.getpass("DeepSeek API key (hidden): ").strip()
        except (getpass.GetPassWarning, EOFError) as error:
            raise ValueError("Cannot read a hidden key; use an interactive terminal") from error
    if not key or any(c.isspace() for c in key):
        raise ValueError("Empty key or whitespace in key")
    subprocess.run(["secret-tool", "store", "--label=Codex DeepSeek API key",
                    *KEY_ATTRIBUTES], input=key, text=True, capture_output=True,
                   check=True, timeout=60)
    if read_key() != key:
        raise ValueError("Keyring verification failed")
    print("Saved credential to the desktop Secret Service keyring")


def read_key() -> str:
    result = subprocess.run(["secret-tool", "lookup", *KEY_ATTRIBUTES],
                            capture_output=True, text=True, timeout=60)
    key = result.stdout.strip()
    if result.returncode or not key or any(c.isspace() for c in key):
        raise ValueError("Unlock your keyring or run codex-deepseek setup-key")
    return key


def check_key() -> None:
    read_key()


def requires_key(args: list[str]) -> bool:
    """Recognise a conservative set of local commands, skipping global option values."""
    local = {'help', 'queue', 'agents', 'archive', 'delete', 'unarchive',
             'migrate-rollouts', 'completion', 'features', 'apply', 'a', 'sandbox', 'logout'}
    values = {'-c', '--config', '--enable', '--disable', '-m', '--model', '-p', '--profile',
              '-s', '--sandbox', '-C', '--cd', '--add-dir', '-a', '--ask-for-approval',
              '--local-provider', '--remote', '--remote-auth-token-env'}
    flags = {'--strict-config', '--oss', '--approve-for-me', '--worktree', '--search',
             '--no-alt-screen', '--no-daemon', '--dangerously-bypass-approvals-and-sandbox',
             '--dangerously-bypass-hook-trust'}
    commands = local | {'exec', 'e', 'review', 'resume', 'fork', 'app-server', 'exec-server',
                        'remote-control', 'cloud', 'update', 'mcp', 'plugin', 'doctor',
                        'debug', 'login'}
    index = 0
    while index < len(args):
        token = args[index]
        if token == '--':
            return True
        if token in {'--help', '-h', '--version', '-V'}:
            return False
        if token in values:
            index += 2
            continue
        if token.partition('=')[0] in values and '=' in token:
            index += 1
            continue
        if len(token) > 2 and token[:2] in values and not token.startswith('--'):
            index += 1  # e.g. -cmodel=x or -C/path
            continue
        if token in flags:
            index += 1
            continue
        if token in local:
            return False
        if token in commands and args[index + 1:] in (['--help'], ['-h']):
            return False
        return True  # prompt, unknown option, or a model-capable command
    return True


def main(args: list[str]) -> int:
    if args and args[0] == 'install':
        raise ValueError('Use python3 install.py from the project directory to install')
    if args and args[0] in ('--install-messaging-skill', '--install-bell-hook', '--dir'):
        # Planning must not create even a project __pycache__ before confirmation.
        sys.dont_write_bytecode = True
        import install as installer
        return installer.run(args, source=HERE)
    if args == ["setup-key"]:
        save_key()
        return 0
    if not (DATA / "config.toml").is_file():
        raise ValueError("Run python3 install.py in the codex-deepseek project first")
    forwarded = args
    if requires_key(args):
        config = tomllib.loads((DATA / 'config.toml').read_text())
        model = config.get('model')
        if model is not None:
            if not isinstance(model, str) or not model.strip():
                raise ValueError('The DeepSeek home must configure a nonempty model name')
            # Project config can include ~/.codex/config.toml when launched from HOME.
            # CLI defaults win over it; later user -c options and explicit -m still win.
            forwarded = ['-c', 'model=' + json.dumps(model), *args]
        check_key()
    env = os.environ.copy()
    # Intended CODEX_HOME override: isolate auth, daemon, history and model catalog.
    env["CODEX_HOME"] = str(DATA)
    for name in ("CODEX_THREAD_ID", "CODEX_SESSION_ID"):
        env.pop(name, None)
    os.execvpe("codex", ["codex", *forwarded], env)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main(sys.argv[1:]))
    except KeyboardInterrupt:
        print("\ncodex-deepseek: cancelled", file=sys.stderr)
        raise SystemExit(130)
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(f"codex-deepseek: {error}", file=sys.stderr)
        raise SystemExit(1)
