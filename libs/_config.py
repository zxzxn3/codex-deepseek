"""Internal model catalog and DeepSeek configuration helpers."""
from __future__ import annotations

import datetime
import json
from pathlib import Path
import shutil
import tomllib

HERE = Path(__file__).resolve().parent.parent

KEY_ATTRIBUTES = ["application", "codex-deepseek", "provider", "deepseek"]
MODELS = ("deepseek-flash", "deepseek-v4-pro")


def catalog() -> dict:
    # Vendored official model metadata; no external project dependency.
    result = json.loads((HERE / "models.json").read_text())
    if {m["slug"] for m in result["models"]} != set(MODELS):
        raise ValueError("Upstream model catalog changed; review before installing")
    return result


def toml_config(data: dict) -> str:
    """Serialize parsed configuration values; comments and formatting are not copied."""
    def value(item):
        if isinstance(item, str):
            return json.dumps(item)
        if isinstance(item, bool):
            return 'true' if item else 'false'
        if isinstance(item, (int, float)):
            return repr(item)
        if isinstance(item, (datetime.datetime, datetime.date, datetime.time)):
            return item.isoformat()
        if isinstance(item, list):
            return '[' + ', '.join(value(v) for v in item) + ']'
        if isinstance(item, dict):
            return '{' + ', '.join(json.dumps(k) + ' = ' + value(v)
                                   for k, v in item.items()) + '}'
        raise ValueError(f'Unsupported configuration value type: {type(item).__name__}')

    lines = []

    def table(items, path=()):
        if path:
            lines.append('[' + '.'.join(json.dumps(k) for k in path) + ']')
        for key, item in items.items():
            if not isinstance(item, dict):
                lines.append(json.dumps(key) + ' = ' + value(item))
        for key, item in items.items():
            if isinstance(item, dict):
                lines.append('')
                table(item, (*path, key))

    table(data)
    return '\n'.join(lines).rstrip() + '\n'


def configuration(base: str = '', *, root: Path | None = None) -> str:
    """Keep Codex defaults, or copied preferences, except required DeepSeek wiring."""
    data = tomllib.loads(base)
    # Named profiles live in separate files and can replace the provider settings.
    # Copying their selection without those files would not be a usable install.
    data.pop('profile', None)
    hooks = data.get('hooks', {})
    if isinstance(hooks, dict):
        hooks.pop('state', None)  # Approval records belong to the source config path.
    data.update(model='deepseek-flash', model_provider='deepseek',
                model_catalog_json=str((root or HERE) / 'models.json'))
    providers = data.setdefault('model_providers', {})
    if not isinstance(providers, dict):
        raise ValueError('model_providers must be a table')
    providers['deepseek'] = {
        'name': 'DeepSeek', 'base_url': 'https://api.deepseek.com',
        'wire_api': 'responses', 'requires_openai_auth': False,
        'supports_websockets': False,
        'auth': {'command': shutil.which('secret-tool') or '/usr/bin/secret-tool',
                 'args': ['lookup', *KEY_ATTRIBUTES], 'refresh_interval_ms': 0},
    }
    result = ('# Generated by codex-deepseek launcher.py install.\n'
              '# Only DeepSeek connection settings override Codex defaults or copied preferences.\n'
              + toml_config(data))
    tomllib.loads(result)
    return result

